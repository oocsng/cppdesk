struct CppDeskWindowLinuxImpl {
    IdentityManager& identity;
    NetworkEngine& network;

    Display* dpy = nullptr;
    bool ownsDisplay = false;
    Window win = 0;
    int screen = 0;
    Visual* visual = nullptr;
    int depth = 0;
    GC gc = nullptr;
    XIM xim = nullptr;
    XIC xic = nullptr;
    Atom wmProtocols = 0, wmDelete = 0, netWmState = 0, netWmStateFullscreen = 0, netActiveWindow = 0,
         netSupported = 0, netWmIcon = 0, gtkThemeVariant = 0, utf8String = 0;
    Cursor cursors[5] = {};
    ui::CursorShape currentCursor = ui::CursorShape::Arrow;

    float scale = 1.0f;
    int widthPx = 0, heightPx = 0;
    bool useShm = false;
    XShmSegmentInfo shm{};
    XImage* image = nullptr;
    cairo_surface_t* surface = nullptr;
    ui::CairoCanvas canvas;

    std::unique_ptr<XdndTarget> dnd;
    // Cleared before teardown so late background callbacks (the update check) find no window.
    std::shared_ptr<std::atomic<CppDeskWindowLinuxImpl*>> liveToken =
        std::make_shared<std::atomic<CppDeskWindowLinuxImpl*>>(this);
    std::unique_ptr<X11Tray> tray;
    bool hiddenInTray = false;
    std::string trayTooltip;
    Atom wmState = 0;
    std::unique_ptr<LinuxShell> shell;
    std::unique_ptr<AppUi> app;

    int wakeFds[2] = { -1, -1 };
    std::mutex postMutex;
    std::vector<std::function<void()>> posted;

    bool closed = false;
    std::atomic<bool> needsPaint{true};   // set from network threads through invalidate()
    bool focused = false;
    bool mapped = false;
    bool relaunch = false;
    unsigned frameIntervalMs = 32;
    Clock::time_point nextTick = Clock::now();
    Clock::time_point lastPaint{};
    std::bitset<256> keys;

    CppDeskWindowLinuxImpl(IdentityManager& id, NetworkEngine& net) : identity(id), network(net) {
        if (pipe2(wakeFds, O_CLOEXEC | O_NONBLOCK) != 0) wakeFds[0] = wakeFds[1] = -1;
    }

    void wake() {
        if (wakeFds[1] >= 0) {
            const char c = 1;
            (void)!write(wakeFds[1], &c, 1);
        }
    }

    void invalidate() {
        needsPaint = true;
        wake();
    }

    void setCursorShape(ui::CursorShape shape) {
        if (!dpy || !win || shape == currentCursor) return;
        currentCursor = shape;
        XDefineCursor(dpy, win, cursors[static_cast<int>(shape)]);
    }

    void sendWmMessage(Atom type, long a0, long a1, long a2, long a3) {
        XEvent ev{};
        ev.xclient.type = ClientMessage;
        ev.xclient.window = win;
        ev.xclient.message_type = type;
        ev.xclient.format = 32;
        ev.xclient.data.l[0] = a0;
        ev.xclient.data.l[1] = a1;
        ev.xclient.data.l[2] = a2;
        ev.xclient.data.l[3] = a3;
        XSendEvent(dpy, RootWindow(dpy, screen), False, SubstructureRedirectMask | SubstructureNotifyMask, &ev);
        XFlush(dpy);
    }

    bool wmSupports(Atom atom) {
        Atom type = 0;
        int format = 0;
        unsigned long count = 0, after = 0;
        unsigned char* data = nullptr;
        bool found = false;
        if (XGetWindowProperty(dpy, RootWindow(dpy, screen), netSupported, 0, 4096, False, XA_ATOM, &type, &format,
                               &count, &after, &data) == Success && data) {
            const Atom* atoms = reinterpret_cast<const Atom*>(data);
            for (unsigned long i = 0; i < count && !found; ++i) found = atoms[i] == atom;
        }
        if (data) XFree(data);
        return found;
    }

    void setThemeVariant(bool dark) {
        if (!dpy || !win) return;
        const char* v = dark ? "dark" : "light";
        XChangeProperty(dpy, win, gtkThemeVariant, utf8String, 8, PropModeReplace,
                        reinterpret_cast<const unsigned char*>(v), static_cast<int>(std::strlen(v)));
        XFlush(dpy);
    }

    void freeBackBuffer() {
        canvas.detach();
        if (app) app->onGraphicsLost();
        if (surface) {
            cairo_surface_destroy(surface);
            surface = nullptr;
        }
        if (image) {
            if (useShm) {
                XShmDetach(dpy, &shm);
                XDestroyImage(image);
                shmdt(shm.shmaddr);
            } else {
                XDestroyImage(image);   // frees the pixel memory too
            }
            image = nullptr;
        }
    }

    // A 32-bit image the size of the window, shared with the X server when it can see our memory.
    void allocateBackBuffer(int w, int h) {
        freeBackBuffer();
        widthPx = std::max(1, w);
        heightPx = std::max(1, h);
        useShm = false;
        if (XShmQueryExtension(dpy)) {
            image = XShmCreateImage(dpy, visual, depth, ZPixmap, nullptr, &shm, widthPx, heightPx);
            if (image) {
                shm.shmid = shmget(IPC_PRIVATE, static_cast<size_t>(image->bytes_per_line) * heightPx, IPC_CREAT | 0600);
                shm.shmaddr = shm.shmid >= 0 ? static_cast<char*>(shmat(shm.shmid, nullptr, 0)) : reinterpret_cast<char*>(-1);
                if (shm.shmaddr != reinterpret_cast<char*>(-1)) {
                    image->data = shm.shmaddr;
                    shm.readOnly = False;
                    XSync(dpy, False);
                    g_xError = false;
                    auto old = XSetErrorHandler(recordXError);
                    XShmAttach(dpy, &shm);
                    XSync(dpy, False);
                    XSetErrorHandler(old);
                    useShm = !g_xError;
                    shmctl(shm.shmid, IPC_RMID, nullptr);   // freed once both sides detach
                    if (!useShm) shmdt(shm.shmaddr);
                } else if (shm.shmid >= 0) {
                    shmctl(shm.shmid, IPC_RMID, nullptr);
                }
                if (!useShm) {
                    image->data = nullptr;
                    XDestroyImage(image);
                    image = nullptr;
                }
            }
        }
        if (!image) {
            char* data = static_cast<char*>(std::calloc(static_cast<size_t>(widthPx) * heightPx, 4));
            image = XCreateImage(dpy, visual, depth, ZPixmap, 0, data, widthPx, heightPx, 32, widthPx * 4);
        }
        surface = cairo_image_surface_create_for_data(reinterpret_cast<unsigned char*>(image->data), CAIRO_FORMAT_RGB24,
                                                      widthPx, heightPx, image->bytes_per_line);
        canvas.attach(surface, scale);
        needsPaint = true;
    }

    void paint() {
        if (!app || !surface || closed) return;
        const auto now = Clock::now();
        const double dt = lastPaint.time_since_epoch().count() == 0
            ? 1.0 / 60.0
            : std::min(0.25, std::chrono::duration<double>(now - lastPaint).count());
        lastPaint = now;
        needsPaint = false;
        app->render(canvas, widthPx / scale, heightPx / scale, dt);
        if (useShm) {
            // Ask for a completion event and wait for it, so the next frame never draws into memory the server is
            // still reading (tearing).
            XShmPutImage(dpy, win, gc, image, 0, 0, 0, 0, widthPx, heightPx, True);
            XEvent done;
            XIfEvent(dpy, &done, [](Display* d, XEvent* e, XPointer) {
                return static_cast<Bool>(e->type == XShmGetEventBase(d) + ShmCompletion);
            }, nullptr);
        }
        else XPutImage(dpy, win, gc, image, 0, 0, 0, 0, widthPx, heightPx);
        XFlush(dpy);
        if (app->wantsAnimationFrame()) needsPaint = true;
    }

    // The window is gone: let the screens finish, then stop the loop.
    void destroyWindow() {
        if (closed) return;
        closed = true;
        if (!dpy || !win) return;   // never created
        if (app) app->onWindowDestroyed();
        tray.reset();
        freeBackBuffer();
        XDestroyWindow(dpy, win);
        XFlush(dpy);
    }

    void requestClose() {
        if (app) app->onCloseRequested();
        destroyWindow();
    }

    bool trayDocked() const { return tray && tray->docked(); }

    // Close or minimize with "minimize to tray" on: withdraw the window; only when a tray can bring it back.
    bool hideToTrayIfWanted() {
        if (!identity.settings().minimizeToTray || !trayDocked()) return false;
        XWithdrawWindow(dpy, win, screen);
        XFlush(dpy);
        hiddenInTray = true;
        return true;
    }

    void restoreFromTray() {
        hiddenInTray = false;
        XMapRaised(dpy, win);
        sendWmMessage(netActiveWindow, 1, CurrentTime, 0, 0);
        NotificationManager* notif = app ? app->notifications() : nullptr;
        if (app) app->restoreFromTray(notif ? notif->lastNotificationType() : NotificationType::GeneralInfo);
        if (notif) notif->clearLastNotificationType();
    }

    bool iconified() {
        Atom type = 0;
        int format = 0;
        unsigned long count = 0, after = 0;
        unsigned char* data = nullptr;
        bool iconic = false;
        if (XGetWindowProperty(dpy, win, wmState, 0, 2, False, wmState, &type, &format, &count, &after, &data) ==
                Success && data && count >= 1) {
            iconic = *reinterpret_cast<long*>(data) == IconicState;
        }
        if (data) XFree(data);
        return iconic;
    }

    // Tray icon, panel and menu events; true when the event belonged to the tray.
    bool handleTrayEvent(const XEvent& ev) {
        if (!tray) return false;
        X11Tray::MenuInfo info;
        if (ev.type == ButtonPress && app) {   // the menu opens on a press; only then are its labels needed
            info.status = app->trayStatusText();
            info.muted = app->notifications() && app->notifications()->isMuted();
        }
        bool consumed = false, lost = false;
        const X11Tray::Action action = tray->handleEvent(ev, info, consumed, lost);
        if (lost && hiddenInTray) restoreFromTray();   // the panel went away: never leave the window unreachable
        switch (action) {
            case X11Tray::Action::Restore: restoreFromTray(); break;
            case X11Tray::Action::ToggleMute: if (app) app->toggleNotificationsMuted(); break;
            case X11Tray::Action::Quit: destroyWindow(); break;
            case X11Tray::Action::Nothing: break;
        }
        return consumed;
    }

    std::string lookupText(XKeyEvent& kev) {
        char buf[64];
        KeySym ks = 0;
        std::string text;
        if (xic) {
            Status status = 0;
            int n = Xutf8LookupString(xic, &kev, buf, sizeof(buf), &ks, &status);
            if (status == XBufferOverflow) {
                std::vector<char> big(static_cast<size_t>(n) + 1);
                n = Xutf8LookupString(xic, &kev, big.data(), n, &ks, &status);
                text.assign(big.data(), static_cast<size_t>(std::max(0, n)));
            } else if (status == XLookupChars || status == XLookupBoth) {
                text.assign(buf, static_cast<size_t>(std::max(0, n)));
            }
        } else {
            // No input context: XLookupString gives Latin-1 bytes; the screens take UTF-8.
            int n = XLookupString(&kev, buf, sizeof(buf), &ks, nullptr);
            for (int i = 0; i < n; ++i) {
                const unsigned char c = static_cast<unsigned char>(buf[i]);
                if (c < 0x80) {
                    text.push_back(static_cast<char>(c));
                } else {
                    text.push_back(static_cast<char>(0xC0 | (c >> 6)));
                    text.push_back(static_cast<char>(0x80 | (c & 0x3F)));
                }
            }
        }
        // X gives Delete a DEL character; Windows' WM_CHAR gives none, and the screens expect that.
        text.erase(std::remove(text.begin(), text.end(), '\x7f'), text.end());
        return text;
    }

    void handleEvent(XEvent& ev);
    bool processEvents(int timeoutMs);
};

// What the screens get from Linux. Without a window (snapshots) it answers with fixed, harmless values.
class LinuxShell : public ui::PlatformShell {
public:
    LinuxShell(CppDeskWindowLinuxImpl* w, bool snapshotMode) : w_(w), snapshotMode_(snapshotMode) {}

    void invalidate() override {
        if (w_) w_->invalidate();
    }
    void setCursor(ui::CursorShape shape) override {
        if (live()) w_->setCursorShape(shape);
    }
    float dpiScale() const override { return w_ ? w_->scale : 1.0f; }
    // Snapshots draw at a fixed instant so clock-driven pulses and timeouts are repeatable.
    uint64_t nowMs() const override {
        if (snapshotMode_) return 10000;
        return static_cast<uint64_t>(
            std::chrono::duration_cast<std::chrono::milliseconds>(Clock::now().time_since_epoch()).count());
    }
    void setTextInputActive(bool active) override {
        if (!live() || !w_->xic) return;
        if (active) XSetICFocus(w_->xic);
        else XUnsetICFocus(w_->xic);
    }

    // shortcut: the dialog blocks the UI thread, so the window does not repaint while it is open; move it to a
    // worker thread with a posted result if that bothers anyone.
    std::optional<std::string> chooseOpenFile(const std::string& title, const std::string& filterName,
                                              const std::string& filterPattern) override {
        if (auto r = spawn::output({ "zenity", "--file-selection", "--title=" + title,
                                     "--file-filter=" + filterName + " | " + filterPattern, "--file-filter=All files | *" })) {
            return r;
        }
        return spawn::output({ "kdialog", "--title", title, "--getopenfilename", ".", filterPattern + "|" + filterName });
    }
    std::optional<std::string> chooseFolder(const std::string& title) override {
        if (auto r = spawn::output({ "zenity", "--file-selection", "--directory", "--title=" + title })) return r;
        return spawn::output({ "kdialog", "--title", title, "--getexistingdirectory", "." });
    }
    void openUrl(const std::string& url) override { spawn::detached({ "xdg-open", url }); }
    void revealPath(const std::string& path) override {
        std::error_code ec;
        const std::filesystem::path p(path);
        spawn::detached({ "xdg-open", std::filesystem::is_directory(p, ec) ? p.string() : p.parent_path().string() });
    }
    // Starting a second copy now would hit the single-instance lock; main re-executes after the loop instead.
    void relaunchApp() override {
        if (!w_) return;
        w_->relaunch = true;
        w_->destroyWindow();
    }
    void setFrameIntervalMs(unsigned ms) override {
        if (w_) w_->frameIntervalMs = std::max(1u, ms);
    }
    bool setFullscreen(bool on) override {
        if (!live() || !w_->wmSupports(w_->netWmStateFullscreen)) return false;
        w_->sendWmMessage(w_->netWmState, on ? 1 : 0, static_cast<long>(w_->netWmStateFullscreen), 0, 1);
        return true;
    }
    void setDarkTitleBar(bool dark) override {
        if (live()) w_->setThemeVariant(dark);
    }
    void quitApp() override {
        if (w_) w_->destroyWindow();
    }
    bool relaunchElevated() override { return false; }
    void playAlertSound() override {
        if (live()) XBell(w_->dpy, 0);
    }
    bool isWindowForeground() const override { return live() && w_->focused && w_->mapped; }
    void bringToFront() override {
        if (!live()) return;
        XMapRaised(w_->dpy, w_->win);
        w_->sendWmMessage(w_->netActiveWindow, 1, CurrentTime, 0, 0);
    }
    // X grabs the pointer for us while a button is held, so drags outside the window keep reporting.
    void setMouseCapture(bool) override {}
    bool isKeyDown(uint16_t vk) const override { return w_ && vk < 256 && w_->keys[vk]; }
    // LeaveNotify is always selected.
    void trackMouseLeave() override {}
    bool loadAppIcon(std::vector<uint8_t>& bgra, int& width, int& height) override {
        return decodeAppIcon(bgra, width, height);
    }

    void checkForUpdates(bool manual) override {
        if (!w_) return;
        // The check can finish after the window is gone; the token is cleared before teardown.
        std::shared_ptr<std::atomic<CppDeskWindowLinuxImpl*>> token = w_->liveToken;
        AutoUpdater::checkForUpdatesAsync([token, manual](const UpdateInfo& info) {
            CppDeskWindowLinuxImpl* w = token->load();
            if (!w) return;
            std::lock_guard<std::mutex> lock(w->postMutex);
            w->posted.push_back([w, info, manual] {
                if (w->app) w->app->onUpdateCheckDone(info, manual);
                w->invalidate();
            });
            w->wake();
        });
    }
    void startUpdateDownload(const std::string&, uint64_t, const std::string&,
                             std::function<void(bool, const std::string&)> done) override {
        if (done) done(false, "Automatic updates are not available on Linux yet.");
    }
    ui::ServiceState serviceState() const override { return ui::ServiceState::NotInstalled; }
    bool runServiceAction(ui::ServiceAction) override { return false; }
    void showNotification(const std::string&, const std::string&) override {}
    void setTrayStatus(const std::string&) override {}

    bool has(ui::Capability c) const override {
        if (c == ui::Capability::TrayIcon) return w_ && w_->trayDocked();
        if (c == ui::Capability::NativeNotifications) return spawn::onPath("notify-send");
        return false;   // the Windows-only controls stay hidden
    }

private:
    bool live() const { return w_ && w_->dpy && w_->win && !w_->closed; }

    CppDeskWindowLinuxImpl* w_ = nullptr;
    bool snapshotMode_ = false;
};

void CppDeskWindowLinuxImpl::handleEvent(XEvent& ev) {
    if (!app) return;
    if (ev.type == MappingNotify) {
        XRefreshKeyboardMapping(&ev.xmapping);
        return;
    }
    if (handleTrayEvent(ev)) return;
    if (ev.xany.window != win) return;   // root and other windows' events (selected by the tray)
    switch (ev.type) {
        case Expose:
            if (ev.xexpose.count == 0) needsPaint = true;
            break;
        case ConfigureNotify:
            if (ev.xconfigure.width != widthPx || ev.xconfigure.height != heightPx) {
                allocateBackBuffer(ev.xconfigure.width, ev.xconfigure.height);
                app->onResized();
            }
            break;
        case MapNotify:
            mapped = true;
            needsPaint = true;
            break;
        case UnmapNotify:
            mapped = false;
            break;
        case FocusIn:
        case FocusOut:
            if (ev.xfocus.detail == NotifyPointer) break;
            focused = ev.type == FocusIn;
            if (!focused) keys.reset();
            // XIM servers (IBus, fcitx) only compose for a focused input context.
            if (xic) focused ? XSetICFocus(xic) : XUnsetICFocus(xic);
            app->onFocusChanged(focused);
            break;
        case MotionNotify:
            app->onMouseMove(ev.xmotion.x / scale, ev.xmotion.y / scale);
            break;
        case LeaveNotify:
            if (ev.xcrossing.mode == NotifyNormal) app->onMouseLeave();
            break;
        case ButtonPress:
        case ButtonRelease: {
            const bool down = ev.type == ButtonPress;
            const float x = ev.xbutton.x / scale, y = ev.xbutton.y / scale;
            switch (ev.xbutton.button) {
                case Button1: keys[kVkLButton] = down; app->onMouseButton(MouseButtonId::Left, down, x, y); break;
                case Button2: keys[kVkMButton] = down; app->onMouseButton(MouseButtonId::Middle, down, x, y); break;
                case Button3: keys[kVkRButton] = down; app->onMouseButton(MouseButtonId::Right, down, x, y); break;
                case Button4: if (down) app->onWheel(0.0f, 120.0f, x, y); break;
                case Button5: if (down) app->onWheel(0.0f, -120.0f, x, y); break;
                case 6: if (down) app->onWheel(-120.0f, 0.0f, x, y); break;
                case 7: if (down) app->onWheel(120.0f, 0.0f, x, y); break;
                default: break;
            }
            break;
        }
        case KeyPress:
        case KeyRelease: {
            const bool down = ev.type == KeyPress;
            const uint16_t vk = InputInjector::mapX11KeySymToVk(static_cast<uint32_t>(XLookupKeysym(&ev.xkey, 0)));
            // A release whose press the input method consumed never reached the screens; drop it too.
            if (vk != 0 && (down || keys[vk])) {
                keys[vk] = down;
                app->onKey(KeyEvent{ vk, 0, down, InputInjector::isExtendedVk(vk) });
            }
            if (down) {
                const std::string text = lookupText(ev.xkey);
                if (!text.empty()) app->onText(text);
            }
            break;
        }
        case SelectionNotify:
            if (auto dropped = dnd ? dnd->handleSelectionNotify(ev) : std::nullopt) {
                app->onFilesDropped(dropped->paths, dropped->x / scale, dropped->y / scale);
            }
            break;
        case PropertyNotify:
            if (ev.xproperty.atom == wmState && iconified()) hideToTrayIfWanted();
            break;
        case ClientMessage:
            if (dnd && dnd->handleClientMessage(ev)) break;
            if (ev.xclient.message_type == wmProtocols && static_cast<Atom>(ev.xclient.data.l[0]) == wmDelete) {
                if (!hideToTrayIfWanted()) requestClose();
            }
            break;
        default:
            break;
    }
    if (!closed) setCursorShape(app->cursorShape());
}

bool CppDeskWindowLinuxImpl::processEvents(int timeoutMs) {
    if (closed || !dpy) return false;
    auto now = Clock::now();
    auto due = now + std::chrono::milliseconds(timeoutMs < 0 ? 60000 : timeoutMs);
    due = std::min(due, nextTick);
    if (needsPaint) due = std::min(due, lastPaint + std::chrono::milliseconds(kMinFrameGapMs));
    XFlush(dpy);
    if (XPending(dpy) == 0) {
        const int waitMs = static_cast<int>(std::max<int64_t>(
            0, std::chrono::duration_cast<std::chrono::milliseconds>(due - now).count()));
        pollfd fds[2] = { { ConnectionNumber(dpy), POLLIN, 0 }, { wakeFds[0], POLLIN, 0 } };
        poll(fds, 2, waitMs);
    }

    char drain[64];
    while (read(wakeFds[0], drain, sizeof(drain)) > 0) {}
    std::vector<std::function<void()>> work;
    {
        std::lock_guard<std::mutex> lock(postMutex);
        work.swap(posted);
    }
    for (auto& fn : work) fn();

    while (!closed && XPending(dpy) > 0) {
        XEvent ev;
        XNextEvent(dpy, &ev);
        if (XFilterEvent(&ev, None)) continue;   // the input method consumed it (compose, IME)
        handleEvent(ev);
    }

    now = Clock::now();
    if (!closed && app && now >= nextTick) {
        app->onTick();
        nextTick = now + std::chrono::milliseconds(frameIntervalMs);
        if (tray) {
            const std::string status = app->trayStatusText();
            if (status != trayTooltip) tray->setTooltip(trayTooltip = status);
        }
    }
    if (!closed && needsPaint && now >= lastPaint + std::chrono::milliseconds(kMinFrameGapMs)) paint();
    return !closed;
}

CppDeskWindow::CppDeskWindow(IdentityManager& identity, NetworkEngine& network, const std::string& autoConnectTarget)
    : identity_(identity), network_(network), autoConnectTarget_(autoConnectTarget),
      pImpl_(std::make_unique<CppDeskWindowLinuxImpl>(identity, network)) {
    pImpl_->shell = std::make_unique<LinuxShell>(pImpl_.get(), false);
    pImpl_->app = std::make_unique<AppUi>(identity_, network_, *pImpl_->shell, autoConnectTarget);

    // Network callbacks arrive on worker threads; hand them to the UI thread.
    CppDeskWindowLinuxImpl* w = pImpl_.get();
    network_.setOnScratchpadUpdateCallback([this](const ScratchpadUpdatePayload& p) {
        post([this, p] { pImpl_->app->onScratchpadUpdate(p); });
    });
    network_.setOnCommandPaletteOutputCallback([this](const CommandPaletteOutputPayload& p) {
        post([this, p] { pImpl_->app->onCommandPaletteOutput(p); });
    });
    network_.setOnFrameDecodedCallback([this, w] {
        if (w->app->claimFrameRedraw()) post([w] { w->app->onFrameReady(); });
    });
    network_.setOnVersionMismatchCallback([this](const std::string& hostVer, const std::string& viewerVer) {
        post([this, hostVer, viewerVer] { pImpl_->app->onPeerVersionMismatch(hostVer, viewerVer); });
    });
    network_.setOnVersionUpgradeNoticeCallback([this](const VersionUpgradeNoticePayload& notice) {
        std::string version = notice.senderVersion;
        post([this, version] { pImpl_->app->onVersionUpgradeNotice(version); });
    });
}

CppDeskWindow::~CppDeskWindow() {
    pImpl_->liveToken->store(nullptr);
    network_.setOnScratchpadUpdateCallback(nullptr);
    network_.setOnCommandPaletteOutputCallback(nullptr);
    network_.setOnFrameDecodedCallback(nullptr);
    network_.setOnVersionMismatchCallback(nullptr);
    network_.setOnVersionUpgradeNoticeCallback(nullptr);
    close();
}

bool CppDeskWindow::create(void* displayContext, int /*showCommand*/) {
    CppDeskWindowLinuxImpl& w = *pImpl_;
    ensureXlibThreads();
    // Typed text must come out as UTF-8 whatever the user's locale says.
    std::setlocale(LC_CTYPE, "");
    if (std::strcmp(nl_langinfo(CODESET), "UTF-8") != 0) std::setlocale(LC_CTYPE, "C.UTF-8");
    XSetLocaleModifiers("");

    w.dpy = displayContext ? static_cast<Display*>(displayContext) : XOpenDisplay(nullptr);
    if (!w.dpy) {
        std::cerr << "CppDesk: could not open the X display. Is DISPLAY set?\n";
        return false;
    }
    w.ownsDisplay = displayContext == nullptr;
    w.screen = DefaultScreen(w.dpy);
    w.visual = DefaultVisual(w.dpy, w.screen);
    w.depth = DefaultDepth(w.dpy, w.screen);
    // shortcut: only the 24/32-bit BGRX TrueColor visual every modern X server uses; add a converting blit if
    // someone runs a 16-bit or big-endian display.
    if ((w.depth != 24 && w.depth != 32) || w.visual->red_mask != 0xFF0000 || w.visual->blue_mask != 0xFF) {
        std::cerr << "CppDesk: unsupported X visual (needs 24-bit TrueColor).\n";
        return false;
    }
    w.scale = UiPlatform::dpiScaleFromXftDpi(XGetDefault(w.dpy, "Xft", "dpi"));

    w.wmProtocols = XInternAtom(w.dpy, "WM_PROTOCOLS", False);
    w.wmDelete = XInternAtom(w.dpy, "WM_DELETE_WINDOW", False);
    w.netWmState = XInternAtom(w.dpy, "_NET_WM_STATE", False);
    w.netWmStateFullscreen = XInternAtom(w.dpy, "_NET_WM_STATE_FULLSCREEN", False);
    w.netActiveWindow = XInternAtom(w.dpy, "_NET_ACTIVE_WINDOW", False);
    w.netSupported = XInternAtom(w.dpy, "_NET_SUPPORTED", False);
    w.netWmIcon = XInternAtom(w.dpy, "_NET_WM_ICON", False);
    w.gtkThemeVariant = XInternAtom(w.dpy, "_GTK_THEME_VARIANT", False);
    w.utf8String = XInternAtom(w.dpy, "UTF8_STRING", False);

    const int offset = (identity_.instanceId() - 1) * 44;
    const int screenW = DisplayWidth(w.dpy, w.screen), screenH = DisplayHeight(w.dpy, w.screen);
    // Fit the screen, but never below the minimum size (WSLg's X screen can report 640x480).
    const int widthPx = std::max(static_cast<int>(kMinWidthDips * w.scale),
                                 std::min(screenW, static_cast<int>(kInitialWidthDips * w.scale)));
    const int heightPx = std::max(static_cast<int>(kMinHeightDips * w.scale),
                                  std::min(screenH, static_cast<int>(kInitialHeightDips * w.scale)));

    XSetWindowAttributes attrs{};
    attrs.background_pixel = BlackPixel(w.dpy, w.screen);
    attrs.event_mask = ExposureMask | KeyPressMask | KeyReleaseMask | ButtonPressMask | ButtonReleaseMask |
                       PointerMotionMask | StructureNotifyMask | FocusChangeMask | EnterWindowMask |
                       LeaveWindowMask | PropertyChangeMask;
    // Keep the window on screen whatever the instance offset, as Windows does with its work area.
    const int x = std::clamp(100 + offset, 0, std::max(0, screenW - widthPx));
    const int y = std::clamp(70 + offset, 0, std::max(0, screenH - heightPx));
    w.win = XCreateWindow(w.dpy, RootWindow(w.dpy, w.screen), x, y, widthPx, heightPx, 0,
                          w.depth, InputOutput, w.visual, CWBackPixel | CWEventMask, &attrs);
    if (!w.win) return false;

    std::string title = "CppDesk";
    if (identity_.instanceId() > 1) title += " #" + std::to_string(identity_.instanceId());
    XStoreName(w.dpy, w.win, title.c_str());
    XChangeProperty(w.dpy, w.win, XInternAtom(w.dpy, "_NET_WM_NAME", False), w.utf8String, 8, PropModeReplace,
                    reinterpret_cast<const unsigned char*>(title.c_str()), static_cast<int>(title.size()));
    XClassHint cls{ const_cast<char*>("cppdesk"), const_cast<char*>("CppDesk") };
    XSetClassHint(w.dpy, w.win, &cls);
    XSetWMProtocols(w.dpy, w.win, &w.wmDelete, 1);
    XSizeHints* hints = XAllocSizeHints();
    hints->flags = PMinSize;
    hints->min_width = static_cast<int>(kMinWidthDips * w.scale);
    hints->min_height = static_cast<int>(kMinHeightDips * w.scale);
    XSetWMNormalHints(w.dpy, w.win, hints);
    XFree(hints);
    {
        std::vector<uint8_t> bgra;
        int iw = 0, ih = 0;
        if (decodeAppIcon(bgra, iw, ih)) {
            std::vector<unsigned long> data{ static_cast<unsigned long>(iw), static_cast<unsigned long>(ih) };
            data.reserve(2 + static_cast<size_t>(iw) * ih);
            for (size_t i = 0; i + 3 < bgra.size(); i += 4) {
                data.push_back(static_cast<unsigned long>(bgra[i]) | (static_cast<unsigned long>(bgra[i + 1]) << 8) |
                               (static_cast<unsigned long>(bgra[i + 2]) << 16) | (static_cast<unsigned long>(bgra[i + 3]) << 24));
            }
            XChangeProperty(w.dpy, w.win, w.netWmIcon, XA_CARDINAL, 32, PropModeReplace,
                            reinterpret_cast<const unsigned char*>(data.data()), static_cast<int>(data.size()));
        }
    }
    w.setThemeVariant(identity_.settings().darkTheme);

    // Held keys repeat as KeyPress only, as on Windows (no KeyRelease between repeats).
    XkbSetDetectableAutoRepeat(w.dpy, True, nullptr);

    w.xim = XOpenIM(w.dpy, nullptr, nullptr, nullptr);
    if (!w.xim) {
        XSetLocaleModifiers("@im=none");
        w.xim = XOpenIM(w.dpy, nullptr, nullptr, nullptr);
    }
    if (w.xim) {
        // Only the "nothing" preedit/status style is drawn here; use the IC only if the input method offers it.
        XIMStyles* styles = nullptr;
        bool styleOk = false;
        if (!XGetIMValues(w.xim, XNQueryInputStyle, &styles, nullptr) && styles) {
            for (unsigned short i = 0; i < styles->count_styles; ++i) {
                styleOk = styleOk || styles->supported_styles[i] == (XIMPreeditNothing | XIMStatusNothing);
            }
            XFree(styles);
        }
        if (styleOk) w.xic = XCreateIC(w.xim, XNInputStyle, XIMPreeditNothing | XIMStatusNothing, XNClientWindow, w.win,
                          XNFocusWindow, w.win, nullptr);
        long imEvents = 0;
        if (w.xic && !XGetICValues(w.xic, XNFilterEvents, &imEvents, nullptr)) {
            XSelectInput(w.dpy, w.win, attrs.event_mask | imEvents);
        }
    }

    const unsigned shapes[5] = { XC_left_ptr, XC_hand2, XC_xterm, XC_sb_h_double_arrow, XC_sb_v_double_arrow };
    for (int i = 0; i < 5; ++i) w.cursors[i] = XCreateFontCursor(w.dpy, shapes[i]);
    XDefineCursor(w.dpy, w.win, w.cursors[0]);

    w.dnd = std::make_unique<XdndTarget>(w.dpy, w.win);
    w.wmState = XInternAtom(w.dpy, "WM_STATE", False);
    {
        std::vector<uint8_t> bgra;
        int iw = 0, ih = 0;
        decodeAppIcon(bgra, iw, ih);
        w.tray = std::make_unique<X11Tray>(w.dpy, w.screen, w.scale, std::move(bgra), iw, ih);
    }
    w.gc = XCreateGC(w.dpy, w.win, 0, nullptr);
    w.allocateBackBuffer(widthPx, heightPx);

    {
        auto notif = std::make_unique<NotificationManager>();
        notif->init(nullptr, nullptr, title);
        w.app->setNotificationManager(std::move(notif));
    }

    XMapWindow(w.dpy, w.win);
    XFlush(w.dpy);
    w.app->startAutoConnect();
    return true;
}

bool CppDeskWindow::processEvents(int timeoutMs) {
    return pImpl_ && pImpl_->processEvents(timeoutMs);
}

int CppDeskWindow::messageLoop() {
    if (!pImpl_ || !pImpl_->dpy || !pImpl_->win) return 1;
    while (processEvents(-1)) {}
    return 0;
}

void CppDeskWindow::post(std::function<void()> fn) {
    {
        std::lock_guard<std::mutex> lock(pImpl_->postMutex);
        pImpl_->posted.push_back(std::move(fn));
    }
    pImpl_->wake();
}

void CppDeskWindow::requestQuit() {
    CppDeskWindowLinuxImpl* w = pImpl_.get();
    post([w] { w->requestClose(); });
}

AppUi& CppDeskWindow::app() { return *pImpl_->app; }

unsigned long CppDeskWindow::nativeWindow() const { return pImpl_ ? pImpl_->win : 0; }

bool CppDeskWindow::relaunchRequested() const { return pImpl_ && pImpl_->relaunch; }

void CppDeskWindow::close() {
    if (!pImpl_) return;
    CppDeskWindowLinuxImpl& w = *pImpl_;
    w.destroyWindow();
    w.app.reset();   // the screens free their images through the canvas
    w.canvas.detach();
    if (w.dpy) {
        if (w.xic) XDestroyIC(w.xic);
        if (w.xim) XCloseIM(w.xim);
        for (Cursor c : w.cursors) if (c) XFreeCursor(w.dpy, c);
        if (w.gc) XFreeGC(w.dpy, w.gc);
        if (w.ownsDisplay) XCloseDisplay(w.dpy);
        w.dpy = nullptr;
    }
    w.xic = nullptr;
    w.xim = nullptr;
    w.gc = nullptr;
    for (int fd : w.wakeFds) if (fd >= 0) ::close(fd);
    w.wakeFds[0] = w.wakeFds[1] = -1;
}

int CppDeskWindow::runUiSnapshots(IdentityManager& identity, NetworkEngine& network, const std::string& outDir) {
    constexpr int kWidth = 1280, kHeight = 800;
    std::error_code ec;
    std::filesystem::create_directories(outDir, ec);
    LinuxShell shell(nullptr, true);
    int written = 0;
    std::string timings;   // average frame time per state
    for (const auto& name : AppUi::snapshotStateNames()) {
        cairo_surface_t* surface = cairo_image_surface_create(CAIRO_FORMAT_ARGB32, kWidth, kHeight);
        {
            ui::CairoCanvas canvas;   // outlives the screens, which free their images through it
            canvas.attach(surface, 1.0f);
            AppUi app(identity, network, shell, "");
            app.applySnapshotState(name);
            // Settle every spring at a fixed step, as the Windows snapshots do.
            constexpr int kFrames = 150, kTimedFrom = 50;
            double drawMs = 0.0;
            for (int frame = 0; frame < kFrames; ++frame) {
                const auto t0 = Clock::now();
                app.render(canvas, kWidth, kHeight, 1.0 / 60.0);
                if (frame >= kTimedFrom) drawMs += std::chrono::duration<double, std::milli>(Clock::now() - t0).count();
            }
            char line[96];
            std::snprintf(line, sizeof(line), "%s %.3f ms\n", name.c_str(), drawMs / (kFrames - kTimedFrom));
            timings += line;
        }
        const std::string path = (std::filesystem::path(outDir) / (name + ".png")).string();
        if (cairo_surface_write_to_png(surface, path.c_str()) == CAIRO_STATUS_SUCCESS) ++written;
        cairo_surface_destroy(surface);
        network.injectViewerFrameForTest({}, 0, 0);
    }
    {
        AppSettings s = identity.settings();
        s.darkTheme = false;
        identity.updateSettings(s);
    }
    std::ofstream(std::filesystem::path(outDir) / "timings.txt", std::ios::trunc) << timings;
    return written;
}

