// Windows virtual-key codes for the mouse buttons, so isKeyDown(VK_LBUTTON) works as on Windows.
constexpr uint16_t kVkLButton = 0x01, kVkRButton = 0x02, kVkMButton = 0x04;

bool decodeAppIcon(std::vector<uint8_t>& bgra, int& width, int& height) {
    struct Reader { const unsigned char* p; size_t left; } reader{ kAppIconPng, kAppIconPngSize };
    cairo_surface_t* s = cairo_image_surface_create_from_png_stream(
        [](void* closure, unsigned char* data, unsigned int length) {
            auto* r = static_cast<Reader*>(closure);
            if (length > r->left) return CAIRO_STATUS_READ_ERROR;
            std::memcpy(data, r->p, length);
            r->p += length;
            r->left -= length;
            return CAIRO_STATUS_SUCCESS;
        },
        &reader);
    const bool ok = cairo_surface_status(s) == CAIRO_STATUS_SUCCESS;
    if (ok) {
        width = cairo_image_surface_get_width(s);
        height = cairo_image_surface_get_height(s);
        const int stride = cairo_image_surface_get_stride(s);
        const uint8_t* src = cairo_image_surface_get_data(s);
        bgra.resize(static_cast<size_t>(width) * height * 4);
        for (int y = 0; y < height; ++y) {
            std::memcpy(bgra.data() + static_cast<size_t>(y) * width * 4, src + static_cast<size_t>(y) * stride,
                        static_cast<size_t>(width) * 4);
        }
    }
    cairo_surface_destroy(s);
    return ok;
}

// XShmAttach fails with BadAccess when the X server cannot see our shared memory (remote displays, WSLg).
bool g_xError = false;
int recordXError(Display*, XErrorEvent*) {
    g_xError = true;
    return 0;
}

