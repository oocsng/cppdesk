    CGContextRef ctx = [[NSGraphicsContext currentContext] CGContext];
    if (!impl_ || !impl_->bitmap) {
        CGContextSetRGBFillColor(ctx, 0, 0, 0, 1);
        CGContextFillRect(ctx, NSRectToCGRect(self.bounds));
        return;
    }
    CGImageRef image = CGBitmapContextCreateImage(impl_->bitmap);   // copy-on-write snapshot of the back buffer
    CGContextSetInterpolationQuality(ctx, kCGInterpolationNone);
    CGContextDrawImage(ctx, NSRectToCGRect(self.bounds), image);
    CGImageRelease(image);
}

