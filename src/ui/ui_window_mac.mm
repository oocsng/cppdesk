    [self addTrackingArea:tracking_];
}

// The pointer in DIPs from the top-left, which is what the screens use (this view is not flipped).
- (NSPoint)dipPoint:(NSEvent*)event {
    NSPoint p = [self convertPoint:event.locationInWindow fromView:nil];
    p.y = self.bounds.size.height - p.y;
    return p;
}

- (void)moved:(NSEvent*)event {
    if (!impl_ || !impl_->app) return;
    NSPoint p = [self dipPoint:event];
    impl_->app->onMouseMove(static_cast<float>(p.x), static_cast<float>(p.y));
}

- (void)button:(cppdesk::MouseButtonId)button vk:(uint16_t)vk down:(BOOL)down event:(NSEvent*)event {
    if (!impl_ || !impl_->app) return;
    impl_->keys[vk] = down;
    NSPoint p = [self dipPoint:event];
    impl_->app->onMouseButton(button, down, static_cast<float>(p.x), static_cast<float>(p.y));
}

- (void)mouseMoved:(NSEvent*)event { [self moved:event]; }
- (void)mouseDragged:(NSEvent*)event { [self moved:event]; }
- (void)rightMouseDragged:(NSEvent*)event { [self moved:event]; }
- (void)otherMouseDragged:(NSEvent*)event { [self moved:event]; }
