// What the screens get from macOS. Without a window (snapshots) it answers with fixed, harmless values.
class MacShell : public ui::PlatformShell {
public:
    MacShell(CppDeskWindowMacImpl* w, bool snapshotMode) : w_(w), snapshotMode_(snapshotMode) {}

    void invalidate() override {
        if (w_) w_->invalidate();
    }
    void setCursor(ui::CursorShape shape) override {
        if (live()) w_->setCursorShape(shape);
    }
    float dpiScale() const override { return w_ ? w_->scale : 1.0f; }
    // Snapshots draw at a fixed instant so clock-driven pulses and timeouts are repeatable.
    uint64_t nowMs() const override {
        if (snapshotMode_) return 10000;
        return static_cast<uint64_t>(
            std::chrono::duration_cast<std::chrono::milliseconds>(Clock::now().time_since_epoch()).count());
    }
    // shortcut: composition is always available and the screens ignore text with no field focused.
    void setTextInputActive(bool) override {}

    // shortcut: the panels block the UI thread (the window does not repaint while one is open), as on Linux.
    std::optional<std::string> chooseOpenFile(const std::string& title, const std::string& /*filterName*/,
                                              const std::string& filterPattern) override {
        @autoreleasepool {
            NSOpenPanel* panel = [NSOpenPanel openPanel];
            panel.title = toNs(title);
            panel.canChooseFiles = YES;
            panel.canChooseDirectories = NO;
            panel.allowsMultipleSelection = NO;
            // "*.avi" -> avi; "*.mp4;*.mov" -> both; "*" -> any file.
            NSMutableArray* types = [NSMutableArray array];
            size_t pos = 0;
            while (pos < filterPattern.size()) {
                size_t end = filterPattern.find(';', pos);
                if (end == std::string::npos) end = filterPattern.size();
                const std::string part = filterPattern.substr(pos, end - pos);
                if (part.size() > 2 && part.compare(0, 2, "*.") == 0) [types addObject:toNs(part.substr(2))];
                pos = end + 1;
            }
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wdeprecated-declarations"
            if (types.count) panel.allowedFileTypes = types;
#pragma clang diagnostic pop
            if ([panel runModal] != NSModalResponseOK || !panel.URL) return std::nullopt;
            return fromNs(panel.URL.path);
        }
    }
    std::optional<std::string> chooseFolder(const std::string& title) override {
        @autoreleasepool {
            NSOpenPanel* panel = [NSOpenPanel openPanel];
            panel.title = toNs(title);
            panel.canChooseFiles = NO;
            panel.canChooseDirectories = YES;
            panel.allowsMultipleSelection = NO;
            if ([panel runModal] != NSModalResponseOK || !panel.URL) return std::nullopt;
            return fromNs(panel.URL.path);
        }
    }
    void openUrl(const std::string& url) override {
        @autoreleasepool {
            NSURL* u = [NSURL URLWithString:toNs(url)];
            if (u) [[NSWorkspace sharedWorkspace] openURL:u];
        }
    }
    void revealPath(const std::string& path) override {
        @autoreleasepool {
            NSURL* u = [NSURL fileURLWithPath:toNs(path)];
            std::error_code ec;
            if (std::filesystem::is_directory(std::filesystem::path(path), ec)) [[NSWorkspace sharedWorkspace] openURL:u];
            else [[NSWorkspace sharedWorkspace] activateFileViewerSelectingURLs:@[ u ]];
        }
    }
    // Starting a second copy now would hit the single-instance lock; main re-executes after the loop instead.
    void relaunchApp() override {
        if (!w_) return;
        w_->relaunch = true;
        w_->destroyWindow();
    }
    void setFrameIntervalMs(unsigned ms) override {
        if (w_) w_->frameIntervalMs = std::max(1u, ms);
    }
    bool setFullscreen(bool on) override {
        if (!live()) return false;
        const bool isFull = (w_->window.styleMask & NSWindowStyleMaskFullScreen) != 0;
        if (isFull != on) [w_->window toggleFullScreen:nil];
        return true;
    }
    void setDarkTitleBar(bool dark) override {
        if (live()) w_->window.appearance = [NSAppearance appearanceNamed:dark ? NSAppearanceNameDarkAqua : NSAppearanceNameAqua];
    }
    void quitApp() override {
        if (w_) w_->destroyWindow();
    }
    bool relaunchElevated() override { return false; }
    void playAlertSound() override { NSBeep(); }
    bool isWindowForeground() const override { return live() && w_->window.isKeyWindow && !w_->window.isMiniaturized; }
    void bringToFront() override {
        if (!live()) return;
        [NSApp activateIgnoringOtherApps:YES];
        [w_->window makeKeyAndOrderFront:nil];
    }
    // AppKit keeps sending a drag's events to the view that started it, outside the window too.
    void setMouseCapture(bool) override {}
    bool isKeyDown(uint16_t vk) const override { return w_ && vk < 256 && w_->keys[vk]; }
    // The tracking area reports the pointer leaving.
    void trackMouseLeave() override {}
    bool loadAppIcon(std::vector<uint8_t>& bgra, int& width, int& height) override {
        return decodeAppIcon(bgra, width, height);
    }

    void checkForUpdates(bool manual) override {
        if (!w_) return;
        // The check can finish after the window is gone; the token is cleared before teardown.
        std::shared_ptr<CppDeskWindowMacImpl::LiveToken> token = w_->liveToken;
        AutoUpdater::checkForUpdatesAsync([token, manual](const UpdateInfo& info) {
            std::lock_guard<std::mutex> alive(token->m);
            CppDeskWindowMacImpl* w = token->w;
            if (!w) return;
            {
                std::lock_guard<std::mutex> lock(w->postMutex);
                w->posted.push_back([w, info, manual] {
                    if (w->app) w->app->onUpdateCheckDone(info, manual);
                    w->invalidate();
                });
            }
            w->wake();
        });
    }
    void startUpdateDownload(const std::string&, uint64_t, const std::string&,
                             std::function<void(bool, const std::string&)> done) override {
        if (done) done(false, "Automatic updates are not available on macOS yet.");
    }
    ui::ServiceState serviceState() const override { return ui::ServiceState::NotInstalled; }
    bool runServiceAction(ui::ServiceAction) override { return false; }
    void showNotification(const std::string&, const std::string&) override {}   // NotificationManager does it
    void setTrayStatus(const std::string&) override {}                           // updated on the loop's tick

    bool has(ui::Capability c) const override {
        if (c == ui::Capability::TrayIcon) return w_ && w_->statusItem != nil;
        if (c == ui::Capability::NativeNotifications) return true;
        return false;   // the Windows-only controls stay hidden
    }

private:
    bool live() const { return w_ && w_->window && !w_->closed; }

    CppDeskWindowMacImpl* w_ = nullptr;
    bool snapshotMode_ = false;
};

void CppDeskWindowMacImpl::wake() {
    // Any thread may post an event to wake the loop; before the app exists the first pass drains the queue anyway.
    if (!NSApp) return;
    NSEvent* ev = [NSEvent otherEventWithType:NSEventTypeApplicationDefined location:NSZeroPoint modifierFlags:0
                                    timestamp:0 windowNumber:0 context:nil subtype:0 data1:0 data2:0];
    [NSApp postEvent:ev atStart:NO];
}

void CppDeskWindowMacImpl::setCursorShape(ui::CursorShape shape) {
    if (!window || shape == currentCursor) return;
    currentCursor = shape;
    [window invalidateCursorRectsForView:view];
}

void CppDeskWindowMacImpl::freeBackBuffer() {
    canvas.detach();
    if (app) app->onGraphicsLost();
    if (bitmap) {
        CGContextRelease(bitmap);
        bitmap = nullptr;
    }
    pixels.clear();
}

// A BGRA buffer the size of the view in pixels, which the canvas draws into and drawRect: shows.
void CppDeskWindowMacImpl::allocateBackBuffer(int w, int h) {
    freeBackBuffer();
    widthPx = std::max(1, w);
    heightPx = std::max(1, h);
    pixels.assign(static_cast<size_t>(widthPx) * heightPx * 4, 0);
    CGColorSpaceRef space = CGColorSpaceCreateDeviceRGB();
    bitmap = CGBitmapContextCreate(pixels.data(), widthPx, heightPx, 8, static_cast<size_t>(widthPx) * 4, space,
                                   kCGImageAlphaPremultipliedFirst | kCGBitmapByteOrder32Little);
    CGColorSpaceRelease(space);
    if (bitmap) canvas.attach(bitmap, scale);
    needsPaint = true;
}

// Follow the view: its size or the screen's scale (moving to another display) changed.
void CppDeskWindowMacImpl::syncBackBuffer() {
    if (!view || !window) return;
    const float s = std::max(1.0f, static_cast<float>(window.backingScaleFactor));
    const NSSize b = view.bounds.size;
    const int w = std::max(1, static_cast<int>(std::lround(b.width * s)));
    const int h = std::max(1, static_cast<int>(std::lround(b.height * s)));
    if (w == widthPx && h == heightPx && s == scale && bitmap) return;
    scale = s;
    allocateBackBuffer(w, h);
    if (app) app->onResized();
}

void CppDeskWindowMacImpl::paint() {
    if (!app || closed || !view) return;
    syncBackBuffer();
    if (!bitmap) return;
    const auto now = Clock::now();
    const double dt = lastPaint.time_since_epoch().count() == 0
        ? 1.0 / 60.0
        : std::min(0.25, std::chrono::duration<double>(now - lastPaint).count());
    lastPaint = now;
    needsPaint = false;
    app->render(canvas, widthPx / scale, heightPx / scale, dt);
    [view setNeedsDisplay:YES];
    [view displayIfNeeded];
    if (app->wantsAnimationFrame()) needsPaint = true;
}

// The window is gone: let the screens finish, then stop the loop.
void CppDeskWindowMacImpl::destroyWindow() {
    if (closed) return;
    closed = true;
    if (!window) return;   // never created
    if (app) app->onWindowDestroyed();
    if (statusItem) {
        [[NSStatusBar systemStatusBar] removeStatusItem:statusItem];
        statusItem = nil;
    }
    freeBackBuffer();
    window.delegate = nil;
    [window orderOut:nil];
    [window close];
}

// Close with "minimize to tray" on: hide the window; the menu-bar item brings it back.
bool CppDeskWindowMacImpl::hideToTrayIfWanted() {
    if (!identity.settings().minimizeToTray || !statusItem) return false;
    [window orderOut:nil];
    hiddenInTray = true;
    return true;
}

void CppDeskWindowMacImpl::restoreFromTray() {
    hiddenInTray = false;
    [NSApp activateIgnoringOtherApps:YES];
    [window makeKeyAndOrderFront:nil];
    NotificationManager* notif = app ? app->notifications() : nullptr;
    if (app) app->restoreFromTray(notif ? notif->lastNotificationType() : NotificationType::GeneralInfo);
    if (notif) notif->clearLastNotificationType();
}

void CppDeskWindowMacImpl::createTray() {
    statusItem = [[NSStatusBar systemStatusBar] statusItemWithLength:NSSquareStatusItemLength];
    NSImage* icon = [[NSImage alloc] initWithData:[NSData dataWithBytes:kAppIconPng length:kAppIconPngSize]];
    if (icon) {
        icon.size = NSMakeSize(18, 18);
        statusItem.button.image = icon;
    } else {
        statusItem.button.title = @"CD";
    }
    NSMenu* menu = [[NSMenu alloc] init];
    NSMenuItem* show = [menu addItemWithTitle:@"Show CppDesk" action:@selector(restore:) keyEquivalent:@""];
    show.target = menuTarget;
    statusLine = [menu addItemWithTitle:@"" action:nil keyEquivalent:@""];
    statusLine.enabled = NO;
    muteItem = [menu addItemWithTitle:@"Mute notifications" action:@selector(toggleMute:) keyEquivalent:@""];
    muteItem.target = menuTarget;
    [menu addItem:[NSMenuItem separatorItem]];
    NSMenuItem* quit = [menu addItemWithTitle:@"Quit CppDesk" action:@selector(quit:) keyEquivalent:@""];
    quit.target = menuTarget;
    statusItem.menu = menu;
}

bool CppDeskWindowMacImpl::processEvents(int timeoutMs) {
    if (closed || !window) return false;
    @autoreleasepool {
        auto now = Clock::now();
        auto due = now + std::chrono::milliseconds(timeoutMs < 0 ? 60000 : timeoutMs);
        due = std::min(due, nextTick);
        if (needsPaint) due = std::min(due, lastPaint + std::chrono::milliseconds(kMinFrameGapMs));
        const double waitSeconds =
            std::max<int64_t>(0, std::chrono::duration_cast<std::chrono::milliseconds>(due - now).count()) / 1000.0;

        // Wait for the first event (or the wake-up post), then drain whatever else is queued.
        NSEvent* ev = [NSApp nextEventMatchingMask:NSEventMaskAny
                                         untilDate:[NSDate dateWithTimeIntervalSinceNow:waitSeconds]
                                            inMode:NSDefaultRunLoopMode
                                           dequeue:YES];
        while (ev && !closed) {
            [NSApp sendEvent:ev];
            ev = [NSApp nextEventMatchingMask:NSEventMaskAny untilDate:[NSDate distantPast]
                                       inMode:NSDefaultRunLoopMode dequeue:YES];
        }

        std::vector<std::function<void()>> work;
        {
            std::lock_guard<std::mutex> lock(postMutex);
            work.swap(posted);
        }
        for (auto& fn : work) {
            if (closed) break;
            fn();
        }

        now = Clock::now();
        if (!closed && app && now >= nextTick) {
            app->onTick();
            nextTick = now + std::chrono::milliseconds(frameIntervalMs);
            const std::string status = app->trayStatusText();
            if (statusItem && status != trayTooltip) {
                trayTooltip = status;
                statusItem.button.toolTip = toNs(status);
                statusLine.title = toNs(status);
            }
            if (muteItem && app->notifications()) {
                muteItem.title = app->notifications()->isMuted() ? @"Unmute notifications" : @"Mute notifications";
            }
        }
        if (!closed && app) setCursorShape(app->cursorShape());
        if (!closed && needsPaint && now >= lastPaint + std::chrono::milliseconds(kMinFrameGapMs)) paint();
    }
    return !closed;
}

CppDeskWindow::CppDeskWindow(IdentityManager& identity, NetworkEngine& network, const std::string& autoConnectTarget)
    : identity_(identity), network_(network), autoConnectTarget_(autoConnectTarget),
      pImpl_(std::make_unique<CppDeskWindowMacImpl>(identity, network)) {
    pImpl_->shell = std::make_unique<MacShell>(pImpl_.get(), false);
    pImpl_->app = std::make_unique<AppUi>(identity_, network_, *pImpl_->shell, autoConnectTarget);

    // Network callbacks arrive on worker threads; hand them to the UI thread.
    CppDeskWindowMacImpl* w = pImpl_.get();
    network_.setOnScratchpadUpdateCallback([this](const ScratchpadUpdatePayload& p) {
        post([this, p] { pImpl_->app->onScratchpadUpdate(p); });
    });
    network_.setOnCommandPaletteOutputCallback([this](const CommandPaletteOutputPayload& p) {
        post([this, p] { pImpl_->app->onCommandPaletteOutput(p); });
    });
    network_.setOnFrameDecodedCallback([this, w] {
        if (w->app->claimFrameRedraw()) post([w] { w->app->onFrameReady(); });
    });
    network_.setOnVersionMismatchCallback([this](const std::string& hostVer, const std::string& viewerVer) {
        post([this, hostVer, viewerVer] { pImpl_->app->onPeerVersionMismatch(hostVer, viewerVer); });
    });
    network_.setOnVersionUpgradeNoticeCallback([this](const VersionUpgradeNoticePayload& notice) {
        std::string version = notice.senderVersion;
        post([this, version] { pImpl_->app->onVersionUpgradeNotice(version); });
    });
}

CppDeskWindow::~CppDeskWindow() {
    {
        std::lock_guard<std::mutex> alive(pImpl_->liveToken->m);
        pImpl_->liveToken->w = nullptr;
    }
    network_.setOnScratchpadUpdateCallback(nullptr);
    network_.setOnCommandPaletteOutputCallback(nullptr);
    network_.setOnFrameDecodedCallback(nullptr);
    network_.setOnVersionMismatchCallback(nullptr);
    network_.setOnVersionUpgradeNoticeCallback(nullptr);
    close();
}

bool CppDeskWindow::create(void* /*displayContext*/, int /*showCommand*/) {
    CppDeskWindowMacImpl& w = *pImpl_;
    @autoreleasepool {
        [NSApplication sharedApplication];
        [NSApp setActivationPolicy:NSApplicationActivationPolicyRegular];
        static bool launched = false;
        if (!launched) {
            launched = true;
            [NSApp finishLaunching];
        }

        w.menuTarget = [[CppDeskMenuTarget alloc] init];
        w.menuTarget->impl_ = &w;
        {   // The application menu: only Quit, which ends the loop the way the close button does.
            NSMenu* bar = [[NSMenu alloc] init];
            NSMenuItem* appItem = [[NSMenuItem alloc] init];
            [bar addItem:appItem];
            NSMenu* appMenu = [[NSMenu alloc] init];
            NSMenuItem* quit = [appMenu addItemWithTitle:@"Quit CppDesk" action:@selector(quit:) keyEquivalent:@"q"];
            quit.target = w.menuTarget;
            appItem.submenu = appMenu;
            [NSApp setMainMenu:bar];
        }

        const NSRect content = NSMakeRect(0, 0, kInitialWidthDips, kInitialHeightDips);
        w.window = [[NSWindow alloc] initWithContentRect:content
                                               styleMask:NSWindowStyleMaskTitled | NSWindowStyleMaskClosable |
                                                         NSWindowStyleMaskMiniaturizable | NSWindowStyleMaskResizable
                                                 backing:NSBackingStoreBuffered
                                                   defer:NO];
        if (!w.window) return false;
        w.window.releasedWhenClosed = NO;
        w.window.contentMinSize = NSMakeSize(kMinWidthDips, kMinHeightDips);
        w.window.collectionBehavior |= NSWindowCollectionBehaviorFullScreenPrimary;
        std::string title = "CppDesk";
        if (identity_.instanceId() > 1) title += " #" + std::to_string(identity_.instanceId());
        w.window.title = toNs(title);
        [w.window center];
        if (identity_.instanceId() > 1) {
            NSPoint o = w.window.frame.origin;
            const CGFloat off = (identity_.instanceId() - 1) * 44;
            [w.window setFrameOrigin:NSMakePoint(o.x + off, o.y - off)];
        }
        w.window.appearance = [NSAppearance appearanceNamed:identity_.settings().darkTheme ? NSAppearanceNameDarkAqua
                                                                                            : NSAppearanceNameAqua];

        w.view = [[CppDeskView alloc] initWithFrame:content];
        w.view->impl_ = &w;
        w.window.contentView = w.view;
        w.delegate = [[CppDeskWindowDelegate alloc] init];
        w.delegate->impl_ = &w;
        w.window.delegate = w.delegate;
        [w.window makeFirstResponder:w.view];
        {
            NSImage* icon = [[NSImage alloc] initWithData:[NSData dataWithBytes:kAppIconPng length:kAppIconPngSize]];
            if (icon) NSApp.applicationIconImage = icon;
        }

        w.createTray();
        w.syncBackBuffer();
        {
            auto notif = std::make_unique<NotificationManager>();
            notif->init(nullptr, nullptr, title);
            w.app->setNotificationManager(std::move(notif));
        }

        [NSApp activateIgnoringOtherApps:YES];
        [w.window makeKeyAndOrderFront:nil];
        w.app->startAutoConnect();
    }
    return true;
}

bool CppDeskWindow::processEvents(int timeoutMs) {
    return pImpl_ && pImpl_->processEvents(timeoutMs);
}

int CppDeskWindow::messageLoop() {
    if (!pImpl_ || !pImpl_->window) return 1;
    while (processEvents(-1)) {}
    return 0;
}

void CppDeskWindow::post(std::function<void()> fn) {
    {
        std::lock_guard<std::mutex> lock(pImpl_->postMutex);
        pImpl_->posted.push_back(std::move(fn));
    }
    pImpl_->wake();
}

void CppDeskWindow::requestQuit() {
    CppDeskWindowMacImpl* w = pImpl_.get();
    post([w] { w->requestClose(); });
}

AppUi& CppDeskWindow::app() { return *pImpl_->app; }

void* CppDeskWindow::nativeWindow() const {
    return pImpl_ && pImpl_->window ? (__bridge void*)pImpl_->window : nullptr;
}

bool CppDeskWindow::relaunchRequested() const { return pImpl_ && pImpl_->relaunch; }

void CppDeskWindow::close() {
    if (!pImpl_) return;
    CppDeskWindowMacImpl& w = *pImpl_;
    w.destroyWindow();
    w.app.reset();   // the screens free their images through the canvas
    w.canvas.detach();
    if (w.bitmap) {
        CGContextRelease(w.bitmap);
        w.bitmap = nullptr;
    }
    w.view = nil;
    w.window = nil;
    w.delegate = nil;
    w.menuTarget = nil;
}

int CppDeskWindow::runUiSnapshots(IdentityManager& identity, NetworkEngine& network, const std::string& outDir) {
    constexpr int kWidth = 1280, kHeight = 800;
    std::error_code ec;
    std::filesystem::create_directories(outDir, ec);
    MacShell shell(nullptr, true);
    int written = 0;
    std::string timings;   // average frame time per state
    for (const auto& name : AppUi::snapshotStateNames()) {
        std::vector<uint8_t> pixels(static_cast<size_t>(kWidth) * kHeight * 4, 0);
        CGColorSpaceRef space = CGColorSpaceCreateDeviceRGB();
        CGContextRef ctx = CGBitmapContextCreate(pixels.data(), kWidth, kHeight, 8, static_cast<size_t>(kWidth) * 4, space,
                                                 kCGImageAlphaPremultipliedFirst | kCGBitmapByteOrder32Little);
        CGColorSpaceRelease(space);
        if (!ctx) continue;
        {
            ui::CGCanvas canvas;   // outlives the screens, which free their images through it
            canvas.attach(ctx, 1.0f);
            AppUi app(identity, network, shell, "");
            app.applySnapshotState(name);
            // Settle every spring at a fixed step, as the Windows snapshots do.
            constexpr int kFrames = 150, kTimedFrom = 50;
            double drawMs = 0.0;
            for (int frame = 0; frame < kFrames; ++frame) {
                const auto t0 = Clock::now();
                app.render(canvas, kWidth, kHeight, 1.0 / 60.0);
                if (frame >= kTimedFrom) drawMs += std::chrono::duration<double, std::milli>(Clock::now() - t0).count();
            }
            char line[96];
            std::snprintf(line, sizeof(line), "%s %.3f ms\n", name.c_str(), drawMs / (kFrames - kTimedFrom));
            timings += line;
        }
        CGImageRef image = CGBitmapContextCreateImage(ctx);
        if (writePng(image, (std::filesystem::path(outDir) / (name + ".png")).string())) ++written;
        if (image) CGImageRelease(image);
        CGContextRelease(ctx);
        network.injectViewerFrameForTest({}, 0, 0);
    }
    {
        AppSettings s = identity.settings();
        s.darkTheme = false;
        identity.updateSettings(s);
    }
    std::ofstream(std::filesystem::path(outDir) / "timings.txt", std::ios::trunc) << timings;
    return written;
}

