// assets/icon.png as premultiplied BGRA.
bool decodeAppIcon(std::vector<uint8_t>& bgra, int& width, int& height) {
    CFDataRef data = CFDataCreate(kCFAllocatorDefault, kAppIconPng, static_cast<CFIndex>(kAppIconPngSize));
    CGImageSourceRef source = CGImageSourceCreateWithData(data, nullptr);
    CGImageRef image = source ? CGImageSourceCreateImageAtIndex(source, 0, nullptr) : nullptr;
    bool ok = false;
    if (image) {
        width = static_cast<int>(CGImageGetWidth(image));
        height = static_cast<int>(CGImageGetHeight(image));
        bgra.assign(static_cast<size_t>(width) * height * 4, 0);
        CGColorSpaceRef space = CGColorSpaceCreateDeviceRGB();
        CGContextRef ctx = CGBitmapContextCreate(bgra.data(), width, height, 8, static_cast<size_t>(width) * 4, space,
                                                 kCGImageAlphaPremultipliedFirst | kCGBitmapByteOrder32Little);
        if (ctx) {
            CGContextDrawImage(ctx, CGRectMake(0, 0, width, height), image);
            CGContextRelease(ctx);
            ok = true;
        }
        CGColorSpaceRelease(space);
        CGImageRelease(image);
    }
    if (source) CFRelease(source);
    CFRelease(data);
    return ok;
}

bool writePng(CGImageRef image, const std::string& path) {
    if (!image) return false;
    CFURLRef url = CFURLCreateFromFileSystemRepresentation(kCFAllocatorDefault, reinterpret_cast<const UInt8*>(path.c_str()),
                                                           static_cast<CFIndex>(path.size()), false);
    CGImageDestinationRef dest = url ? CGImageDestinationCreateWithURL(url, CFSTR("public.png"), 1, nullptr) : nullptr;
    bool ok = false;
    if (dest) {
        CGImageDestinationAddImage(dest, image, nullptr);
        ok = CGImageDestinationFinalize(dest);
        CFRelease(dest);
    }
    if (url) CFRelease(url);
    return ok;
}

NSString* toNs(const std::string& utf8) {
    NSString* s = [[NSString alloc] initWithBytes:utf8.data() length:utf8.size() encoding:NSUTF8StringEncoding];
    return s ? s : @"";
}

std::string fromNs(NSString* s) { return s ? std::string([s UTF8String]) : std::string(); }

