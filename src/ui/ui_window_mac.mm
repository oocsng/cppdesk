- (void)otherMouseUp:(NSEvent*)event { [self button:cppdesk::MouseButtonId::Middle vk:0x04 down:NO event:event]; }

- (void)mouseExited:(NSEvent*)event {
    if (impl_ && impl_->app) impl_->app->onMouseLeave();
}

- (void)scrollWheel:(NSEvent*)event {
    if (!impl_ || !impl_->app) return;
    NSPoint p = [self dipPoint:event];
    // The screens count 120 units per wheel notch. A trackpad reports points (about 40 per notch); a mouse wheel
    // reports lines.
    const double k = event.hasPreciseScrollingDeltas ? 3.0 : 120.0;
    const float dy = static_cast<float>(event.scrollingDeltaY * k);
    const float dx = static_cast<float>(-event.scrollingDeltaX * k);   // Windows: positive is "scrolled right"
    if (dx != 0.0f || dy != 0.0f) impl_->app->onWheel(dx, dy, static_cast<float>(p.x), static_cast<float>(p.y));
}

- (void)keyDown:(NSEvent*)event {
    if (!impl_ || !impl_->app) return;
    using cppdesk::InputInjector;
    const uint16_t vk = InputInjector::mapMacKeyCodeToVk(event.keyCode);
    if (vk != 0) {
        impl_->keys[vk] = true;
        impl_->app->onKey(cppdesk::KeyEvent{ vk, 0, true, InputInjector::isExtendedVk(vk) });
    }
    if (event.modifierFlags & (NSEventModifierFlagCommand | NSEventModifierFlagControl)) {
        // A shortcut, not typing. Windows delivers Ctrl+letter as a control character (Ctrl+A is 1, C is 3).
        NSString* c = event.charactersIgnoringModifiers;
        if (c.length == 1) {
            unichar ch = [c characterAtIndex:0];
            if (ch >= 'A' && ch <= 'Z') ch += 'a' - 'A';
            if (ch >= 'a' && ch <= 'z') impl_->app->onText(std::string(1, static_cast<char>(ch - 'a' + 1)));
        }
        return;
    }
    if (!marked_.length) {
        // Return, Delete, Tab and Escape are commands to AppKit's text system; Windows' WM_CHAR gives them as
        // characters, which is what the screens expect. (While an input method is composing it gets them instead.)
        switch (event.keyCode) {
            case 0x24: case 0x4C: impl_->app->onText("\r"); return;
            case 0x33: impl_->app->onText("\b"); return;
            case 0x30: impl_->app->onText("\t"); return;
            case 0x35: impl_->app->onText("\x1b"); return;
            default: break;
        }
    }
    [self interpretKeyEvents:@[ event ]];   // typed text arrives through insertText: below
}

- (void)keyUp:(NSEvent*)event {
    if (!impl_ || !impl_->app) return;
    using cppdesk::InputInjector;
    const uint16_t vk = InputInjector::mapMacKeyCodeToVk(event.keyCode);
    if (vk != 0 && impl_->keys[vk]) {
        impl_->keys[vk] = false;
        impl_->app->onKey(cppdesk::KeyEvent{ vk, 0, false, InputInjector::isExtendedVk(vk) });
    }
}

- (void)flagsChanged:(NSEvent*)event {
    if (!impl_ || !impl_->app) return;
    using cppdesk::InputInjector;
    NSEventModifierFlags mask = 0;
    switch (event.keyCode) {
        case 0x38: case 0x3C: mask = NSEventModifierFlagShift; break;
        case 0x3B: case 0x3E: mask = NSEventModifierFlagControl; break;
        case 0x3A: case 0x3D: mask = NSEventModifierFlagOption; break;
        case 0x37: case 0x36: mask = NSEventModifierFlagCommand; break;
        default: return;   // Caps Lock and the rest do not matter to the screens
    }
    const bool down = (event.modifierFlags & mask) != 0;
    const uint16_t vk = InputInjector::mapMacKeyCodeToVk(event.keyCode);
    if (vk == 0 || down == impl_->keys[vk]) return;   // Command and Control share VK_CONTROL
    impl_->keys[vk] = down;
    impl_->app->onKey(cppdesk::KeyEvent{ vk, 0, down, InputInjector::isExtendedVk(vk) });
}

