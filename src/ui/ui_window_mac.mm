- (void)resetCursorRects {
    NSCursor* cursor = [NSCursor arrowCursor];
    if (impl_) {
        switch (impl_->currentCursor) {
            case cppdesk::ui::CursorShape::Arrow: cursor = [NSCursor arrowCursor]; break;
            case cppdesk::ui::CursorShape::Hand: cursor = [NSCursor pointingHandCursor]; break;
            case cppdesk::ui::CursorShape::IBeam: cursor = [NSCursor IBeamCursor]; break;
            case cppdesk::ui::CursorShape::ResizeH: cursor = [NSCursor resizeLeftRightCursor]; break;
            case cppdesk::ui::CursorShape::ResizeV: cursor = [NSCursor resizeUpDownCursor]; break;
        }
    }
    [self addCursorRect:self.bounds cursor:cursor];
}

